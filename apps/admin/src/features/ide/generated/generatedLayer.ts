/**
 * The DCMS-owned files of a Mode B site, from the editor's side.
 *
 * <p>The server writes three things into a site and keeps them current: the typed API client in
 * `src/api/`, the analytics and consent runtime in `src/dcms/`, and `openapi.json`. It records
 * what it wrote in `src/api/manifest.json` — a fingerprint of the output and the list of files.
 * Everything here is about applying a newer copy of that set without ever touching a file the
 * author wrote.</p>
 *
 * <p>Pure, so the rules that decide what an automatic refresh may write and delete are tested
 * without a store, a query client or a server.</p>
 */

export const MANIFEST_PATH = 'src/api/manifest.json';

/** The header the generator writes on its client. How a site from before manifests is recognised. */
const GENERATED_HEADER = '// AUTO-GENERATED by DCMS';

const OWNED_PREFIXES = ['src/api/', 'src/dcms/'];

export interface GeneratedManifest {
  fingerprint: string;
  files: string[];
}

/** Mirrors `GeneratedLayer.Owns` on the server. Anything else in a site belongs to its author. */
export function isGeneratedPath(path: string): boolean {
  return path === 'openapi.json' || OWNED_PREFIXES.some((prefix) => path.startsWith(prefix));
}

export function readManifest(raw: string | undefined): GeneratedManifest | null {
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw) as Partial<GeneratedManifest>;
    if (typeof parsed.fingerprint !== 'string' || !Array.isArray(parsed.files)) return null;
    return { fingerprint: parsed.fingerprint, files: parsed.files.filter((f) => typeof f === 'string') };
  } catch {
    // A manifest somebody edited into invalid JSON is not a reason to stop the editor — it is
    // treated as absent, and the next refresh writes a good one.
    return null;
  }
}

/**
 * Whether this site takes the generated layer at all.
 *
 * <p>A site with a manifest does. So does one scaffolded before manifests existed, recognisable by
 * the generator's header on its client — it is refreshed once and has a manifest from then on.
 * A site whose author never used the generated client has neither, and is left alone: writing an
 * API client into a project that did not ask for one is not a refresh.</p>
 */
export function usesGeneratedLayer(files: Readonly<Record<string, string>>): boolean {
  return files[MANIFEST_PATH] !== undefined || (files['src/api/index.ts'] ?? '').startsWith(GENERATED_HEADER);
}

export interface GeneratedUpdate {
  /** Files to create or overwrite, only where the content actually differs. */
  writes: [path: string, content: string][];
  /** Files the generator used to write and no longer does. */
  deletes: string[];
}

/**
 * What applying `incoming` to `current` changes.
 *
 * <p>Deletion is the dangerous half, so it is narrow on purpose: a file is removed only when the
 * site's <b>own</b> manifest says the generator wrote it, it is inside a generated folder, and the
 * new set no longer has it. A file an author added beside the client — `src/api/extra.ts` — is in
 * a generated folder but not in any manifest, and so survives. A site with no manifest yet gets
 * no deletions at all: there is no record of what was the generator's.</p>
 */
export function planGeneratedUpdate(
  current: Readonly<Record<string, string>>,
  incoming: Readonly<Record<string, string>>,
): GeneratedUpdate {
  const writes = Object.entries(incoming)
    .filter(([path, content]) => isGeneratedPath(path) && current[path] !== content)
    .sort(([a], [b]) => a.localeCompare(b));

  const previous = readManifest(current[MANIFEST_PATH]);
  const deletes = (previous?.files ?? [])
    .filter((path) => isGeneratedPath(path) && !(path in incoming) && current[path] !== undefined)
    .sort();

  return { writes, deletes };
}
