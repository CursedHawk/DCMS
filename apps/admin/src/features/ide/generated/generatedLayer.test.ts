import { describe, expect, it } from 'vitest';
import {
  MANIFEST_PATH,
  isGeneratedPath,
  planGeneratedUpdate,
  readManifest,
  usesGeneratedLayer,
} from './generatedLayer';

const manifest = (fingerprint: string, files: string[]) =>
  JSON.stringify({ fingerprint, files: [...files, MANIFEST_PATH] });

describe('isGeneratedPath', () => {
  it('owns the client, the runtime and the document, and nothing an author writes', () => {
    expect(isGeneratedPath('src/api/index.ts')).toBe(true);
    expect(isGeneratedPath('src/dcms/analytics.ts')).toBe(true);
    expect(isGeneratedPath('openapi.json')).toBe(true);

    expect(isGeneratedPath('src/App.tsx')).toBe(false);
    expect(isGeneratedPath('src/lib/api.ts')).toBe(false);
    expect(isGeneratedPath('src/apiary.ts')).toBe(false);
    expect(isGeneratedPath('docs/openapi.json')).toBe(false);
  });
});

describe('usesGeneratedLayer', () => {
  it('recognises a site by its manifest, or by the generator header from before manifests', () => {
    expect(usesGeneratedLayer({ [MANIFEST_PATH]: manifest('a', []) })).toBe(true);
    expect(usesGeneratedLayer({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS. Do not edit' })).toBe(true);
  });

  it('leaves alone a site that never used the generated client', () => {
    expect(usesGeneratedLayer({ 'src/App.tsx': 'x' })).toBe(false);
    // An author's own src/api folder is not an invitation.
    expect(usesGeneratedLayer({ 'src/api/index.ts': 'export const mine = 1;' })).toBe(false);
  });
});

describe('readManifest', () => {
  it('treats a damaged manifest as absent rather than failing', () => {
    expect(readManifest('{ not json')).toBeNull();
    expect(readManifest(JSON.stringify({ fingerprint: 1 }))).toBeNull();
    expect(readManifest(undefined)).toBeNull();
  });
});

describe('planGeneratedUpdate', () => {
  it('writes only files whose content changed', () => {
    const current = { 'src/api/index.ts': 'old', 'src/api/types.ts': 'same' };
    const incoming = { 'src/api/index.ts': 'new', 'src/api/types.ts': 'same' };

    expect(planGeneratedUpdate(current, incoming)).toEqual({
      writes: [['src/api/index.ts', 'new']],
      deletes: [],
    });
  });

  it('never writes outside the generated folders, whatever the server sends', () => {
    const plan = planGeneratedUpdate({ 'src/App.tsx': 'mine' }, { 'src/App.tsx': 'theirs', 'openapi.json': '{}' });
    expect(plan.writes.map(([p]) => p)).toEqual(['openapi.json']);
  });

  it('deletes a file the previous manifest recorded and the new set dropped', () => {
    const current = {
      [MANIFEST_PATH]: manifest('old', ['src/api/index.ts', 'src/api/legacy.ts']),
      'src/api/index.ts': 'x',
      'src/api/legacy.ts': 'x',
    };
    const incoming = { [MANIFEST_PATH]: manifest('new', ['src/api/index.ts']), 'src/api/index.ts': 'x' };

    expect(planGeneratedUpdate(current, incoming).deletes).toEqual(['src/api/legacy.ts']);
  });

  it('keeps a file an author added beside the client, because no manifest ever listed it', () => {
    const current = {
      [MANIFEST_PATH]: manifest('old', ['src/api/index.ts']),
      'src/api/index.ts': 'x',
      'src/api/helpers.ts': 'the author wrote this',
    };
    const incoming = { [MANIFEST_PATH]: manifest('new', ['src/api/index.ts']), 'src/api/index.ts': 'y' };

    expect(planGeneratedUpdate(current, incoming).deletes).toEqual([]);
  });

  it('deletes nothing on a site with no manifest yet, since nothing records what was generated', () => {
    const current = { 'src/api/index.ts': '// AUTO-GENERATED by DCMS', 'src/api/old.ts': 'x' };
    expect(planGeneratedUpdate(current, { 'src/api/index.ts': 'y' }).deletes).toEqual([]);
  });

  it('refuses to delete an author file even if an edited manifest names it', () => {
    const current = { [MANIFEST_PATH]: manifest('old', ['src/App.tsx']), 'src/App.tsx': 'mine' };
    expect(planGeneratedUpdate(current, { [MANIFEST_PATH]: manifest('new', []) }).deletes).toEqual([]);
  });
});
