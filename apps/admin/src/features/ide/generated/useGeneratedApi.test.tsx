import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { act, renderHook, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { api } from '../../../lib/api';
import { useVfs } from '../../site-source/vfs';
import { API_FINGERPRINT_KEY, useGeneratedApi } from './useGeneratedApi';
import { MANIFEST_PATH } from './generatedLayer';

vi.mock('../../../lib/api', () => ({
  api: { get: vi.fn(), post: vi.fn(), put: vi.fn(), patch: vi.fn(), del: vi.fn(), upload: vi.fn() },
}));
vi.mock('sonner', () => ({ toast: { success: vi.fn(), error: vi.fn() } }));

/**
 * The automatic half of the generated API client: when it rewrites a site's files, and — the part
 * that matters more — when it must not.
 */

const manifest = (fingerprint: string) =>
  JSON.stringify({ fingerprint, files: ['src/api/index.ts', MANIFEST_PATH] });

/** The server: `serverFingerprint` now, and the files that fingerprint stands for. */
function serve(serverFingerprint: { current: string }) {
  vi.mocked(api.get).mockImplementation(async (path: string) => {
    if (path === '/admin/api-fingerprint') return { fingerprint: serverFingerprint.current };
    if (path.endsWith('/generated-files')) {
      return {
        fingerprint: serverFingerprint.current,
        files: {
          'src/api/index.ts': `// AUTO-GENERATED by DCMS ${serverFingerprint.current}`,
          [MANIFEST_PATH]: manifest(serverFingerprint.current),
        },
      };
    }
    throw new Error(`unmocked ${path}`);
  });
}

const generatedFetches = () =>
  vi.mocked(api.get).mock.calls.filter(([path]) => String(path).endsWith('/generated-files')).length;

function setup(settled = true) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const wrapper = ({ children }: { children: React.ReactNode }) => (
    <QueryClientProvider client={client}>{children}</QueryClientProvider>
  );
  const hook = renderHook(({ ready }) => useGeneratedApi({ siteId: 's1', settled: ready }), {
    wrapper,
    initialProps: { ready: settled },
  });
  return { client, hook };
}

function loadSite(files: Record<string, string>) {
  useVfs.getState().load(files, 1, {});
}

describe('useGeneratedApi', () => {
  beforeEach(() => {
    vi.mocked(api.get).mockReset();
    useVfs.setState({ agentRuns: 0 });
  });

  it('refreshes a site whose client is behind the tenant, and writes the new files', async () => {
    const server = { current: 'fp-2' };
    serve(server);
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });

    setup();

    await waitFor(() => expect(useVfs.getState().files['src/api/index.ts']).toBe('// AUTO-GENERATED by DCMS fp-2'));
    expect(JSON.parse(useVfs.getState().files[MANIFEST_PATH]).fingerprint).toBe('fp-2');
    // It lands as an ordinary pending edit, so it autosaves and shows in source control.
    expect(useVfs.getState().dirtyPaths.has('src/api/index.ts')).toBe(true);
  });

  it('does nothing when the site is already current', async () => {
    serve({ current: 'fp-1' });
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });

    const { hook } = setup();

    await waitFor(() => expect(hook.result.current.stale).toBe(false));
    await waitFor(() => expect(api.get).toHaveBeenCalledWith('/admin/api-fingerprint'));
    await new Promise((r) => setTimeout(r, 50));
    expect(generatedFetches()).toBe(0);
  });

  it('holds off during an agent run and refreshes when it ends', async () => {
    serve({ current: 'fp-2' });
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });
    useVfs.getState().beginAgentRun();

    const { hook } = setup();

    // Wait until the hook knows the site is behind — the moment it would otherwise act — and then
    // give it time to. Asserting as soon as the fingerprint was *requested* proves nothing: the
    // answer has not reached the effect yet, so a missing hold would pass too.
    await waitFor(() => expect(hook.result.current.stale).toBe(true));
    await new Promise((r) => setTimeout(r, 50));
    expect(generatedFetches()).toBe(0);

    act(() => useVfs.getState().endAgentRun());
    await waitFor(() => expect(generatedFetches()).toBe(1));
  });

  it('never asks while the draft is unsettled', async () => {
    serve({ current: 'fp-2' });
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });

    setup(false);

    await new Promise((r) => setTimeout(r, 30));
    expect(api.get).not.toHaveBeenCalled();
  });

  it('leaves alone a site that never used the generated client', async () => {
    serve({ current: 'fp-2' });
    loadSite({ 'src/App.tsx': 'export const App = () => null;' });

    setup();

    await new Promise((r) => setTimeout(r, 30));
    expect(api.get).not.toHaveBeenCalled();
    expect(useVfs.getState().files['src/api/index.ts']).toBeUndefined();
  });

  it('refreshes again when the hub says plugins changed — pushed, not polled', async () => {
    const server = { current: 'fp-1' };
    serve(server);
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });

    const { client } = setup();
    await waitFor(() => expect(api.get).toHaveBeenCalledWith('/admin/api-fingerprint'));
    await new Promise((r) => setTimeout(r, 50));
    expect(generatedFetches()).toBe(0);

    // What `LIVE_QUERY_MAP.plugins` does when a plugin instance changes.
    server.current = 'fp-2';
    await act(() => client.invalidateQueries({ queryKey: API_FINGERPRINT_KEY }));

    await waitFor(() => expect(JSON.parse(useVfs.getState().files[MANIFEST_PATH]).fingerprint).toBe('fp-2'));
  });

  it('does not retry in a loop when the server keeps answering with a different fingerprint', async () => {
    // The fingerprint endpoint and the files disagree (a plugin changed between the two calls).
    vi.mocked(api.get).mockImplementation(async (path: string) =>
      path === '/admin/api-fingerprint'
        ? { fingerprint: 'fp-2' }
        : { fingerprint: 'fp-3', files: { [MANIFEST_PATH]: manifest('fp-3') } },
    );
    loadSite({ 'src/api/index.ts': '// AUTO-GENERATED by DCMS fp-1', [MANIFEST_PATH]: manifest('fp-1') });

    setup();

    await waitFor(() => expect(generatedFetches()).toBe(1));
    await new Promise((r) => setTimeout(r, 50));
    expect(generatedFetches()).toBe(1);
  });
});
