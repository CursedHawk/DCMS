import { writeFileSync } from 'node:fs';
import { loadProfile, targets } from './lib/config.mjs';
import { edgeSession } from './lib/auth.mjs';
import { AdminApi } from './lib/api.mjs';
const profile = await loadProfile('vps1', { overrides: {} });
const t = targets(profile);
const session = await edgeSession({ admin: t.admin, username: profile.auth.username, password: profile.auth.password });
const api = new AdminApi({ base: t.admin, session }).forTenant('da-stress');
const sdk = await api.get('/api/admin/plugins/fnload/_functions/sdk');
const files = (await api.post('/api/admin/contracts/functions.code@1/ReadFiles?instance=fnload&plane=admin', {})).files;
const cs = Object.fromEntries(Object.entries(files).filter(([k]) => k.endsWith('.cs')));
writeFileSync(process.argv[2], JSON.stringify({ files: cs, sdk: sdk.csharp }));
console.log('sdk chars', sdk.csharp.length, 'files', Object.keys(cs));
